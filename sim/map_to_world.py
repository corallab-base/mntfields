#!/usr/bin/env python3
"""
Turn a SLAM occupancy grid of the real maze into simulation worlds:
  <name>.npz  for scripts/sim_jackal_2d.py --map
  <name>.sdf  Gazebo world (walls = merged boxes of occupied cells)

Walls are thickened by one cell, but only into unknown space, so free space and
passage widths stay as mapped while lidar rays cannot leak through 1-cell walls.

Grab the live map (read-only) and convert it:
    python3 sim/map_to_world.py --grab --name real_maze      # from /map on the network
    python3 sim/map_to_world.py --npz map.npz --name real_maze
"""

import argparse
import os

import numpy as np
from scipy.ndimage import binary_dilation

HERE = os.path.dirname(os.path.abspath(__file__))


def grab_map(timeout=15.0):
    import rclpy
    from nav_msgs.msg import OccupancyGrid
    from rclpy.qos import DurabilityPolicy, QoSProfile, ReliabilityPolicy

    rclpy.init()
    node = rclpy.create_node("map_grabber")
    got = []
    qos = QoSProfile(depth=1, durability=DurabilityPolicy.TRANSIENT_LOCAL,
                     reliability=ReliabilityPolicy.RELIABLE)
    node.create_subscription(OccupancyGrid, "/map", got.append, qos)
    import time
    end = time.time() + timeout
    while not got and time.time() < end:
        rclpy.spin_once(node, timeout_sec=0.1)
    node.destroy_node()
    rclpy.shutdown()
    if not got:
        raise SystemExit("no /map received")
    m = got[-1]
    i = m.info
    return (np.array(m.data, np.int8).reshape(i.height, i.width), i.resolution,
            i.origin.position.x, i.origin.position.y)


def thicken(data):
    occ = data > 50
    unknown = data < 0
    return occ | (binary_dilation(occ, np.ones((3, 3), bool)) & unknown)


def merge_boxes(occ):
    """Row runs of occupied cells, merged vertically into rectangles (r0, r1, c0, c1)."""
    boxes, open_runs = [], {}
    for r in range(occ.shape[0]):
        row = np.concatenate([[False], occ[r], [False]])
        edges = np.flatnonzero(row[1:] != row[:-1])
        runs = set(zip(edges[0::2], edges[1::2]))
        nxt = {}
        for run in runs:
            if run in open_runs:
                nxt[run] = open_runs.pop(run)
            else:
                nxt[run] = r
        for (c0, c1), r0 in open_runs.items():
            boxes.append((r0, r, c0, c1))
        open_runs = nxt
    for (c0, c1), r0 in open_runs.items():
        boxes.append((r0, occ.shape[0], c0, c1))
    return boxes


def write_sdf(path, name, occ, res, ox, oy, height=0.8):
    models = []
    for k, (r0, r1, c0, c1) in enumerate(merge_boxes(occ)):
        sx, sy = (c1 - c0) * res, (r1 - r0) * res
        x, y = ox + (c0 + c1) / 2 * res, oy + (r0 + r1) / 2 * res
        models.append(
            f"      <collision name='c{k}'><pose>{x:.3f} {y:.3f} {height / 2} 0 0 0</pose>"
            f"<geometry><box><size>{sx:.3f} {sy:.3f} {height}</size></box></geometry></collision>\n"
            f"      <visual name='v{k}'><pose>{x:.3f} {y:.3f} {height / 2} 0 0 0</pose>"
            f"<geometry><box><size>{sx:.3f} {sy:.3f} {height}</size></box></geometry>"
            f"<material><ambient>0.6 0.6 0.65 1</ambient><diffuse>0.6 0.6 0.65 1</diffuse></material></visual>")
    body = "\n".join(models)
    with open(path, "w") as f:
        f.write(f"""<?xml version='1.0'?>
<!-- Generated by sim/map_to_world.py from a SLAM map of the real maze. -->
<sdf version='1.9'>
  <world name='{name}'>
    <physics type='ode'><max_step_size>0.003</max_step_size><real_time_factor>1.0</real_time_factor>
      <real_time_update_rate>333</real_time_update_rate></physics>
    <plugin name='gz::sim::systems::Physics' filename='libgz-sim-physics-system.so'/>
    <plugin name='gz::sim::systems::UserCommands' filename='libgz-sim-user-commands-system.so'/>
    <plugin name='gz::sim::systems::SceneBroadcaster' filename='libgz-sim-scene-broadcaster-system.so'/>
    <plugin name='gz::sim::systems::Sensors' filename='libgz-sim-sensors-system.so'><render_engine>ogre2</render_engine></plugin>
    <plugin name='gz::sim::systems::Imu' filename='libgz-sim-imu-system.so'/>
    <plugin name='gz::sim::systems::NavSat' filename='libgz-sim-navsat-system.so'/>
    <spherical_coordinates><surface_model>EARTH_WGS84</surface_model><latitude_deg>43.500720</latitude_deg>
      <longitude_deg>-80.546793</longitude_deg><elevation>329</elevation><heading_deg>0</heading_deg></spherical_coordinates>
    <scene><ambient>0.8 0.8 0.8 1</ambient><background>0.7 0.8 0.9 1</background><shadows>false</shadows></scene>
    <light type='directional' name='sun'><cast_shadows>false</cast_shadows><pose>0 0 10 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse><direction>-0.3 0.2 -0.9</direction></light>
    <model name='ground_plane'><static>true</static><link name='link'>
      <collision name='collision'><geometry><plane><normal>0 0 1</normal><size>60 60</size></plane></geometry></collision>
      <visual name='visual'><geometry><plane><normal>0 0 1</normal><size>60 60</size></plane></geometry>
        <material><ambient>0.85 0.85 0.85 1</ambient><diffuse>0.85 0.85 0.85 1</diffuse></material></visual>
    </link></model>
    <model name='maze'><static>true</static><link name='walls'>
{body}
    </link></model>
  </world>
</sdf>
""")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    src = p.add_mutually_exclusive_group(required=True)
    src.add_argument("--grab", action="store_true", help="read /map from the network")
    src.add_argument("--npz", help="npz with data, res, ox, oy")
    p.add_argument("--name", default="real_maze")
    args = p.parse_args()
    if args.grab:
        data, res, ox, oy = grab_map()
    else:
        z = np.load(args.npz)
        data, res, ox, oy = z["data"], float(z["res"]), float(z["ox"]), float(z["oy"])
    occ = thicken(data)
    out = np.where(occ, 100, np.where(data < 0, -1, 0)).astype(np.int8)
    npz = os.path.join(HERE, "maps", f"{args.name}.npz")
    np.savez(npz, data=out, res=res, ox=ox, oy=oy)
    sdf = os.path.join(HERE, "worlds", f"{args.name}.sdf")
    write_sdf(sdf, args.name, occ, res, ox, oy)
    print(f"map {data.shape[1] * res:.1f} x {data.shape[0] * res:.1f} m -> {npz}, {sdf} "
          f"({len(merge_boxes(occ))} wall boxes)")


if __name__ == "__main__":
    main()
